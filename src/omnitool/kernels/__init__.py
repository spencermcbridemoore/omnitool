"""CUDA C kernel templates (``.cu``) and the Python templating that inserts
the problem-specific right-hand side (ADR 0004). The device source is plain
C, compiled only through ``omnitool.backends.nvrtc``.

:func:`render_dopri5` is the whole templater: it writes a prelude (scalar
type, sizes, status codes, tableau, the ``rhs`` function) and appends
``dopri5.cu`` unchanged. The compile-time parameters are ``real_t``,
``N_STATE``, ``N_PARAMS`` and the right-hand-side body (spec §4); the tableau
is rendered from ``omnitool.tableaus.dopri5`` and the status codes are the
text of ``status.h``, so neither is typed a second time.
"""

from __future__ import annotations

import re
from functools import cache
from pathlib import Path

import numpy as np

from omnitool.tableaus import dopri5 as tab

__all__ = ["C_TYPES", "render_dopri5", "step_modes"]

_KERNEL_DIR = Path(__file__).resolve().parent
_STATUS_H = _KERNEL_DIR.parent / "status.h"
_DOPRI5_CU = _KERNEL_DIR / "dopri5.cu"

C_TYPES: dict[type[np.floating], str] = {np.float32: "float", np.float64: "double"}
"""The C spelling of ``real_t`` for each supported precision."""


@cache
def _read(path: Path) -> str:
    return path.read_text(encoding="utf-8")


@cache
def step_modes() -> dict[str, int]:
    """The ``STEP_MODE_*`` codes of ``dopri5.cu``, read from the kernel source."""
    found = re.findall(r"^#define STEP_MODE_(\w+)\s+(\d+)", _read(_DOPRI5_CU), flags=re.MULTILINE)
    return {name: int(value) for name, value in found}


def render_dopri5(rhs_body: str, n_state: int, n_params: int, dtype: type[np.floating]) -> str:
    """Return the complete device source of the DOPRI5 kernel for one problem.

    ``rhs_body`` is the body of
    ``void rhs(real_t t, const real_t* y, real_t* dydt, const real_t* p)``;
    floating constants in it are written ``REAL(0.5)`` so they take the type
    of ``real_t``.
    """
    if dtype not in C_TYPES:
        raise ValueError(f"dtype must be one of {tuple(t.__name__ for t in C_TYPES)}, got {dtype}")
    if n_state < 1:
        raise ValueError(f"n_state must be at least 1, got {n_state}")
    if n_params < 0:
        raise ValueError(f"n_params must be non-negative, got {n_params}")
    eps = float(np.finfo(dtype).eps)
    prelude = [
        "/* Generated by omnitool.kernels.render_dopri5; do not edit. */",
        f"typedef {C_TYPES[dtype]} real_t;",
        f"#define N_STATE {int(n_state)}",
        f"#define N_PARAMS {int(n_params)}",
        f"#define REAL_EPS ((real_t){eps:.17g})",
        f"#define DOPRI5_ORDER {tab.ORDER}",
        "",
        _read(_STATUS_H).rstrip("\n"),
        "",
        tab.render_c().rstrip("\n"),
        "",
        "#define REAL(x) ((real_t)(x))",
        "static __device__ void rhs(real_t t, const real_t* y, real_t* dydt, const real_t* p)",
        "{",
        '#line 1 "rhs_body"',
        rhs_body.strip("\n"),
        "}",
        "",
        '#line 1 "dopri5.cu"',
    ]
    return "\n".join(prelude) + "\n" + _read(_DOPRI5_CU)
